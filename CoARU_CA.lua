local function stripColor(t)
    local c = t:match("^(|c%x%x%x%x%x%x%x%x)")
    local base = t
    if c then base = base:gsub("^|c%x%x%x%x%x%x%x%x", "", 1):gsub("|r$", "") end
    return base, c
end

local function retext(frame, depth)
    if not frame or depth > 10 then return end
    if frame.GetRegions then
        local ok, regions = pcall(function() return { frame:GetRegions() } end)
        if ok then
            for _, r in ipairs(regions) do
                if r and r.GetObjectType and r:GetObjectType() == "FontString" then
                    local t = r:GetText()
                    if t then
                        local base, color = stripColor(t)
                        local ru = T[base]
                        if ru then
                            if color then ru = color .. ru .. "|r" end
                            pcall(function() r:SetText(ru) end)
                        end
                    end
                end
            end
        end
    end
    if frame.GetChildren then
        local ok, children = pcall(function() return { frame:GetChildren() } end)
        if ok then
            for _, c in ipairs(children) do retext(c, depth + 1) end
        end
    end
end

local hooked = false
local function tryHook()
    if hooked or not CoATalentFrame then return end
    hooked = true
    CoATalentFrame:HookScript("OnShow", function(self) retext(self, 0) end)
    local acc = 0
    CoATalentFrame:HookScript("OnUpdate", function(self, elapsed)
        acc = acc + (elapsed or 0)
        if acc >= 0.3 then acc = 0; retext(self, 0) end
    end)
    if CoATalentFrame:IsShown() then retext(CoATalentFrame, 0) end
end

local waiter = CreateFrame("Frame")
waiter:RegisterEvent("PLAYER_LOGIN")
waiter:RegisterEvent("ADDON_LOADED")
local pacc = 0
local function stopIfHooked()
    if hooked then
        waiter:UnregisterAllEvents()
        waiter:SetScript("OnUpdate", nil)
    end
end
waiter:SetScript("OnEvent", function() tryHook(); stopIfHooked() end)
waiter:SetScript("OnUpdate", function(_, elapsed)
    pacc = pacc + (elapsed or 0)
    if pacc >= 1 then pacc = 0; tryHook(); stopIfHooked() end
end)

local function measureFrame()
    local f = CreateFrame("Frame", nil, UIParent)
    f:SetWidth(1); f:SetHeight(1)
    f:SetPoint("TOPLEFT", UIParent, "TOPLEFT", -5000, 0)
    f:Show()
    local fs = f:CreateFontString(nil, "ARTWORK", "GameFontNormal")
    fs:SetPoint("TOPLEFT")
    fs:SetJustifyH("CENTER")
    return f, fs
end

function CoARU_CA_Fit()
    local specW = 1294
    if CoATalentFrame and CoATalentFrame.SpecView then
        local ok, w = pcall(function() return CoATalentFrame.SpecView:GetWidth() end)
        if ok and type(w) == "number" and w > 100 then specW = w end
    else
        print("CoARU: CoATalentFrame ещё не создан — беру ширину по умолчанию 1294." ..
              " Точнее будет, если сперва открыть экран талантов.")
    end

    local f, fs = measureFrame()
    local function height(text, width)
        fs:SetWidth(width)
        fs:SetText(text)
        return fs:GetStringHeight() or 0
    end

    local report, bad, tested = {}, 0, 0
    for _, numSpecs in ipairs({ 3, 4 }) do
        local width = (specW / numSpecs) * 0.6
        for en, ru in pairs(T) do

            if #en > 60 then
                local he = height(en, width)
                local hr = height(ru, width)
                tested = tested + 1
                if hr > he + 0.5 then
                    bad = bad + 1
                    report[#report + 1] = {
                        specs = numSpecs, width = width, en = en, ru = ru,
                        he = he, hr = hr,
                    }
                end
            end
        end
    end
    f:Hide()

    CoARU_DB = CoARU_DB or {}
    CoARU_DB.cafit = report

    print(("CoARU cafit: ширина SpecView %d; проверок %d (по 3 и 4 спека)."):format(specW, tested))
    if bad == 0 then
        print("|cff00ff00Все описания укладываются в габарит английского — вёрстка безопасна.|r")
    else
        print(("|cffff0000Выше английского: %d|r — покажу до 10, остальное в /reload + дамп:"):format(bad))
        for i = 1, math.min(10, #report) do
            local r = report[i]
            print(("  [%d спека, ширина %.0f] en=%.0fpx ru=%.0fpx: %s"):format(
                r.specs, r.width, r.he, r.hr, r.ru:sub(1, 60)))
        end
    end
end
